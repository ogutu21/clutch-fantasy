// Rebuilds avatars-library.js from the pictures in the "avatars" folder.
// Run it from the project folder after adding or removing pictures:   node update-avatars.js
// Then deploy:   firebase deploy --only hosting
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "avatars");
if (!fs.existsSync(dir)) fs.mkdirSync(dir);

const files = fs.readdirSync(dir).filter(function (f) { return /\.(png|jpe?g|webp)$/i.test(f); }).sort();
const good = [], skipped = [];
files.forEach(function (f) {
  // The game only accepts letters, numbers, dash, underscore and dot in picture file names.
  if (/^[\w\-.]+$/.test(f)) good.push(f); else skipped.push(f);
});

function title(f) {
  return f.replace(/\.[^.]+$/, "").replace(/[-_]+/g, " ").replace(/\b\w/g, function (c) { return c.toUpperCase(); });
}

const lines = good.map(function (f) { return "  { name: " + JSON.stringify(title(f)) + ", src: " + JSON.stringify("avatars/" + f) + " },"; });
const out =
  "// Generated by update-avatars.js from the pictures in the \"avatars\" folder. Run `node update-avatars.js` again after adding or removing pictures.\n" +
  "// Only use art you made or have the right to use.\n" +
  "window.AVATAR_LIBRARY = [\n" + lines.join("\n") + (lines.length ? "\n" : "") + "];\n";
fs.writeFileSync(path.join(__dirname, "avatars-library.js"), out);

console.log("Listed " + good.length + " picture(s) in avatars-library.js.");
if (skipped.length) {
  console.log("Skipped (rename them using only letters, numbers, - and _, no spaces):");
  skipped.forEach(function (f) { console.log("  " + f); });
}
